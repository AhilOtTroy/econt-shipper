function officeText() {
  const [city, q] = pick(OFFICE_PHRASES);
  const r = rnd();
  if (!q) return pick(['офис ' + city, 'Еконт ' + city, city + ', офис на Еконт', 'до офис в ' + city, city]);
  if (r < 0.15) return city + ' офис ' + q;
  if (r < 0.3) return 'офис ' + q + ' ' + city;
  if (r < 0.42) return 'Еконт ' + city + ', ' + q;
  if (r < 0.52) return city + ' - ' + q;
  if (r < 0.62) return 'до офис ' + q + ' в ' + city;
  if (r < 0.7) return city + ' ' + q;
  if (r < 0.76) return 'еконт ' + city.toLowerCase() + ' ' + q.toLowerCase();
  if (r < 0.82) return city + ', кв. ' + q;
  if (r < 0.88) return 'офис Еконт гр. ' + city + ' ' + q;
  if (r < 0.94) return q + ', ' + city;
  return 'Еконтомат ' + city + (city === 'Варна' ? ' Гранд Мол' : city === 'София' ? ' Ринг Мол' : '');
}
