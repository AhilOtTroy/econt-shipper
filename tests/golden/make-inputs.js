function singleMessage() {
  const name = person(), ph = phone();
  const parts = { name, ph };
  const door = chance(0.12);
  const loc = door ? addressText() : officeText();
  const cod = chance(0.55) ? codText() : '';
  const rev = chance(0.35) ? reviewText() : '';
  const style = int(0, 9);
  let msg;
  switch (style) {
    case 0: msg = [name, ph, loc, cod, rev].filter(Boolean).join(' '); break;
    case 1: msg = [name, ph, loc, cod, rev].filter(Boolean).join('\n'); break;
    case 2: msg = ['Име: ' + name, 'Тел: ' + ph, (door ? 'Адрес: ' : 'Офис: ') + loc, cod ? 'Наложен платеж: ' + cod : '', rev].filter(Boolean).join('\n'); break;
    case 3: msg = pick(GREET) + ', ' + pick(BEFORE) + '. ' + (door ? 'Изпратете на ' : 'Изпратете до ') + loc + '. ' + name + ', ' + ph + '. ' + [cod, rev].filter(Boolean).join(', ') + (chance(0.5) ? ' ' + pick(CLOSE) : ''); break;
    case 4: msg = ph + ' ' + name + ', ' + loc + (cod ? ', ' + cod : '') + (rev ? ' ' + rev : ''); break;
    case 5: msg = pick(LISTING) + '\n' + pick(GREET) + ', ' + pick(BEFORE) + '. ' + name + ' ' + ph + ' ' + loc + (rev ? '\n' + rev : ''); break;
    case 6: msg = [pick(NOISE), pick(GREET), name + ' ' + ph, loc, pick(NOISE), cod].filter(Boolean).join('\n'); break;
    case 7: msg = loc + '\n' + name + ' - ' + ph + (cod ? '\n' + cod : '') + (rev ? '\n' + rev : ''); break;
    case 8: msg = pick(GREET) + '! ' + name + ' ' + ph + ' ' + loc + '. ' + (chance(0.5) ? 'Ако не вдигам, звънете на мъжа ми ' + phone() + '. ' : '') + [cod, rev].filter(Boolean).join(' '); break;
    default: msg = name + '\n' + ph + '\n' + loc + (cod ? '\n' + cod : '') + (chance(0.3) ? '\n' + pick(CLOSE) : ''); break;
  }
  void parts;
  return msg.replace(/[ \t]+$/gm, '').trim();
}

function batchMessage() {
  const n = int(2, 7);
  const style = int(0, 6);
  const rows = [];
  for (let i = 0; i < n; i++) {
    const name = person(), ph = phone();
    const loc = chance(0.1) ? addressText() : officeText();
    const cod = chance(0.6) ? codText() : '';
    const rev = chance(0.2) ? reviewText() : '';
    const track = chance(0.08) ? String(1051602900000 + int(100, 99999)) : '';
    if (style === 0) rows.push([name, ph, loc, cod, rev, track].filter(Boolean).join(' '));
    else if (style === 1) rows.push((i + 1) + '. ' + [name, ph, loc, cod, rev].filter(Boolean).join(' '));
    else if (style === 2) rows.push([name, ph, loc, cod, rev].filter(Boolean).join('\n'));
    else if (style === 3) rows.push(['Име: ' + name, 'Телефон: ' + ph, 'Офис: ' + loc, cod ? 'Сума: ' + cod : ''].filter(Boolean).join('\n'));
    else if (style === 4) rows.push(pick(LISTING) + '\n' + name + ' ' + ph + '\n' + loc + (cod ? ' ' + cod : ''));
    else if (style === 5) rows.push(ph + ' ' + name + ' ' + loc + (cod ? ' - ' + cod : ''));
    else rows.push([pick(NOISE), name + ', ' + ph + ', ' + loc, cod].filter(Boolean).join('\n'));
  }
  const sep = style === 0 || style === 1 || style === 5 ? (chance(0.5) ? '\n' : '\n\n') : '\n\n';
  let text = rows.join(sep);
  if (chance(0.25)) text = pick(['Поръчки за днес:', 'Пратки 16.10:', 'За изпращане:', 'Здравейте, ето поръчките:']) + '\n' + text;
  if (chance(0.2)) text += '\n' + pick(['Всички с преглед', 'Всички с наложен платеж', 'Благодаря!', 'Всички до офис']);
  return text;
}

