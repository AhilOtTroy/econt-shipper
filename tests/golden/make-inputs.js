function person() {
  const f = chance(0.55);
  const first = pick(f ? FEMALE : MALE), s = pick(SURN)[f ? 1 : 0];
  const r = rnd();
  if (r < 0.12) return first;                       // first name only
  if (r < 0.2) return (first + ' ' + s).toUpperCase().replace(/^(.)(.*)$/, (m, a, b) => a + b.toLowerCase()); // odd casing
  if (r < 0.26) return first.toLowerCase() + ' ' + s.toLowerCase();
  return first + ' ' + s;
}
let PHONE_SEQ = 0;
function phone() {
  PHONE_SEQ++;
  const op = pick(['87', '88', '89', '88', '89']);
  const d = String(1000000 + ((PHONE_SEQ * 7919 + int(0, 999)) % 9000000)).slice(-7);
  const n = '0' + op + d.charAt(0) + d.slice(1); // 0 8x ddddddd
  const body = n.slice(1);
  switch (int(0, 8)) {
    case 0: return n;
    case 1: return n.slice(0, 4) + ' ' + n.slice(4, 7) + ' ' + n.slice(7);
    case 2: return n.slice(0, 4) + '-' + n.slice(4, 7) + '-' + n.slice(7);
    case 3: return '+359' + body;
    case 4: return '+359 ' + body.slice(0, 3) + ' ' + body.slice(3, 6) + ' ' + body.slice(6);
    case 5: return '00359' + body;
    case 6: return n.slice(0, 4) + '/' + n.slice(4);
    case 7: return '(' + n.slice(0, 4) + ') ' + n.slice(4, 7) + ' ' + n.slice(7);
    default: return n.slice(0, 4) + ' ' + n.slice(4, 6) + ' ' + n.slice(6, 8) + ' ' + n.slice(8);
  }
}

